// Downloads and prepares the 3D models from Poly Pizza (https://poly.pizza), then writes
// assets/models/<id>.glb and js/data/models.js (credits + raw proportions).
//
//   node tools/models.mjs
//
// For each model: keep only the idle animation (used to pose rigged models — nothing animates in
// the app), recolour where asked, drop everything unused. The app scales each model evenly so
// that its `fit` measurement (height `h` or length `w`) matches the real object.
import { writeFile, mkdir } from 'node:fs/promises';
import { NodeIO, getBounds } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { prune, dedup } from '@gltf-transform/functions';

// `turn`: degrees about the vertical axis so the model's length runs along +x (front toward +x).
// `lay`: true for things modelled standing up that should lie on the ground (a coin).
// `glow`: material name → colour it gives off at night. `recolor`: material name → new colour.
const MODELS = [
  { id: 'person', poly: 'HMnuH5geEG', fit: 'h', idle: /Man_Idle$/ },
  { id: 'dog', poly: 'y4wdQpg767', fit: 'w', turn: 90, idle: /^Idle$/ },
  { id: 'car', poly: 'unqqkULtRU', fit: 'w', turn: 90, recolor: { LightBlue: '#d94848' }, glow: { Headlights: '#fff1c2', TailLights: '#ff4436' } },
  { id: 'tree', poly: '9nvGuZlbpE', fit: 'h' },
  { id: 'bus', poly: '4CPpvEmrMoF', fit: 'w', turn: 90 },
  { id: 'house', poly: 'htvFgnVP4d', fit: 'h', glow: { window: '#ffc66b' } },
  { id: 'apartment', poly: 'ppwtREejXg', fit: 'h', glow: { window: '#ffc66b' } },
  { id: 'airliner', poly: 'a3XrQkLNna9', fit: 'w', turn: 90 },
  { id: 'chair', poly: 'iMNqRzPwwe', fit: 'h' },
  { id: 'phone', poly: 'k2kgBepoMU', fit: 'w', lay: true, turn: 90 },
  { id: 'coin', poly: '7IrL01B97W', fit: 'w', lay: true },
];

const get = async url => {
  const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res;
};
const hex = c => [1, 3, 5].map(i => (parseInt(c.slice(i, i + 2), 16) / 255) ** 2.2); // sRGB → linear

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
await mkdir(new URL('../assets/models/', import.meta.url), { recursive: true });
const out = {};

for (const spec of MODELS) {
  const page = await (await get(`https://poly.pizza/m/${spec.poly}`)).text();
  const state = JSON.parse(page.match(/window\.__SERVER_APP_STATE__\s*=\s*(\{.*?\})\s*<\/script>/s)[1]);
  const info = state.initialData.model;
  const glb = new Uint8Array(await (await get(`https://static.poly.pizza/${info.ResourceID}.glb`)).arrayBuffer());

  const doc = await io.readBinary(glb);
  const root = doc.getRoot();
  for (const animation of root.listAnimations()) {
    if (spec.idle?.test(animation.getName())) continue;
    // Disposing an animation alone leaves its keyframe data behind.
    for (const sampler of animation.listSamplers()) {
      sampler.getInput()?.dispose();
      sampler.getOutput()?.dispose();
      sampler.dispose();
    }
    animation.listChannels().forEach(channel => channel.dispose());
    animation.dispose();
  }
  for (const material of root.listMaterials()) {
    const color = spec.recolor?.[material.getName()];
    if (color) material.setBaseColorFactor([...hex(color), 1]);
  }
  await doc.transform(prune(), dedup());
  const bytes = await io.writeBinary(doc);
  await writeFile(new URL(`../assets/models/${spec.id}.glb`, import.meta.url), bytes);

  const b = getBounds(root.listScenes()[0]);
  out[spec.id] = {
    file: `assets/models/${spec.id}.glb`,
    size: b.max.map((v, i) => Number((v - b.min[i]).toPrecision(5))),
    fit: spec.fit,
    ...(spec.turn ? { turn: spec.turn } : {}),
    ...(spec.lay ? { lay: true } : {}),
    ...(spec.glow ? { glow: spec.glow } : {}),
    credit: { title: info.Title, author: info.Creator.Username, licence: info.Licence, url: `https://poly.pizza/m/${spec.poly}` },
  };
  console.log(`${spec.id.padEnd(10)} ${String(Math.round(bytes.length / 1024)).padStart(5)} KB  ${info.Licence.padEnd(9)} ${info.Creator.Username} — ${info.Title}`);
}

await writeFile(new URL('../js/data/models.js', import.meta.url), `// Generated by tools/models.mjs — do not edit by hand.
// Downloaded 3D models: file, raw size [x, y, z] as modelled, which measurement the app scales
// to (\`fit\`: h = height, w = length), orientation fixes, night glow, and the credit.
export const MODELS = ${JSON.stringify(out, null, 2)};
`);
